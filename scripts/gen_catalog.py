#!/usr/bin/env python3
"""Generate docs/CATALOG.md — a browsable inventory built from SKILL.md frontmatter.

This is documentation for humans choosing what to read, NOT the agents' discovery
path. Every supported harness lists installed skills with their descriptions to the
model on its own (pi builds an <available_skills> block; Claude Code and Codex render
equivalent listings), so an in-repo index would be a second, staler copy of something
the runtime already provides — see docs/MAINTAINERS.md.

Usage:
  scripts/gen_catalog.py           # write the catalogue
  scripts/gen_catalog.py --check   # exit 1 if it is out of date (CI)
"""

import pathlib
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent


def yaml_module():
    try:
        import yaml
    except ImportError:
        import subprocess

        subprocess.check_call([sys.executable, "-m", "pip", "install", "-q", "pyyaml"])
        import yaml
    return yaml


def load_skills():
    yaml = yaml_module()
    skills = []
    for path in sorted(ROOT.glob("skills/*/SKILL.md")):
        fm = yaml.safe_load(path.read_text().split("---", 2)[1])
        skills.append(fm)
    return skills




def render_catalog(skills):
    lines = [
        "<!-- GENERATED by scripts/gen_catalog.py from SKILL.md frontmatter — do not edit -->",
        "",
        "# Skill catalog",
        "",
        f"{len(skills)} skills — agent methodology, portable by construction. `requires` legend:",
        "empty = needs nothing but a repo; `external:github` = uses GitHub. Skills that depend on a",
        "platform's capabilities live in that consumer's own overlay, not here. `expects-local` names",
        "the consumer-local slot a skill defers concrete values to (see templates/local-skills/).",
        "",
        "| Skill | Tier | Requires | Expects local | Description |",
        "|---|---|---|---|---|",
    ]
    for s in skills:
        req = ", ".join(s["requires"]) if s["requires"] else "—"
        slots = ", ".join(s.get("expects-local", [])) or "—"
        desc = s["description"].replace("|", "\\|")
        lines.append(f"| `{s['name']}` | {s['tier']} | {req} | {slots} | {desc} |")
    return "\n".join(lines) + "\n"


def main():
    check = "--check" in sys.argv
    skills = load_skills()
    outputs = {ROOT / "docs" / "CATALOG.md": render_catalog(skills)}
    stale = []
    for path, content in outputs.items():
        current = path.read_text() if path.exists() else None
        if current == content:
            continue
        if check:
            stale.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(exist_ok=True)
            path.write_text(content)
            print(f"wrote {path.relative_to(ROOT)}")
    if check:
        if stale:
            print("generated artifacts out of date — run scripts/gen_catalog.py and commit:")
            print("\n".join(f"  {s}" for s in stale))
            sys.exit(1)
        print("docs/CATALOG.md is current")


if __name__ == "__main__":
    main()
